// --- 區塊 / 文字 helper ---------------------------------------------------

let _k = 0;
const uid = () => `ln-${++_k}`;

// rich text 片段：純文字 s()、粗體 b()
const s = (text) => ({ plain_text: text, annotations: {} });
const b = (text) => ({ plain_text: text, annotations: { bold: true } });

// 把字串或 rich-text 片段正規化成 rich_text 陣列
const rich = (x) => (Array.isArray(x) ? x : [s(x)]);

const para = (...parts) => ({
  id: uid(), type: 'paragraph', has_children: false,
  paragraph: { rich_text: parts.length === 1 ? rich(parts[0]) : parts, color: 'default' },
});
const heading = (level) => (...parts) => ({
  id: uid(), type: `heading_${level}`, has_children: false,
  [`heading_${level}`]: { rich_text: parts.length === 1 ? rich(parts[0]) : parts, color: 'default' },
});
const h1 = heading(1);
const h2 = heading(2);
const h3 = heading(3);

const quote = (...parts) => ({
  id: uid(), type: 'quote', has_children: false,
  quote: { rich_text: parts.length === 1 ? rich(parts[0]) : parts, color: 'default' },
});

const divider = () => ({ id: uid(), type: 'divider', has_children: false, divider: {} });

// 項目清單 / 編號清單：items 內每項可為字串或 rich-text 陣列
const listItem = (variant) => (item) => ({
  id: uid(), type: variant, has_children: false,
  [variant]: { rich_text: rich(item), color: 'default' },
});
const bullets = (items) => items.map(listItem('bulleted_list_item'));
const numbers = (items) => items.map(listItem('numbered_list_item'));

// 表格：rows 為二維陣列，每格可為字串或 rich-text 陣列；\n 於前台以 pre-line 換行
const table = (hasColumnHeader, rows) => ({
  id: uid(), type: 'table', has_children: true,
  table: { table_width: rows[0].length, has_column_header: hasColumnHeader, has_row_header: false },
  children: rows.map((cells) => ({
    id: uid(), type: 'table_row', has_children: false,
    table_row: { cells: cells.map(rich) },
  })),
});

